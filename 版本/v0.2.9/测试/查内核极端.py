import io
import contextlib

用例 = [
    ('核说("a\\tb")', "a\tb", "制表符转义"),
    ('核说("反斜杠 \\\\ 保留")', "反斜杠 \\ 保留", "反斜杠转义"),
    ('核说("「中文引号」")', "「中文引号」", "中文引号原样"),
    ('核说("含\\"转义引号\\"")', '含"转义引号"', "转义双引号"),
    ("核说('单引号里 \"双引号\"')", '单引号里 "双引号"', "单引号包双引号"),
    ('核说("多行\\n换行")', "多行\n换行", "换行转义"),
    ('核说("全角，。；！")', "全角，。；！", "全角标点原样"),
    # —— 0.2.4 修：raw 串里的中文引号不能转义 ——
    # 规范化源码 会把 「」 折成 ASCII 引号；对普通串要给内容里同款引号
    # 加反斜杠（否则产物非法），但 raw 串里反斜杠是**字面字符**，
    # 加了之后运行值凭空多出反斜杠。实测曾产出 r"他说\"你好\"",
    # 运行打印 他说\"你好\" —— 与「内容保持原样」的承诺相违。
    ("核说(r「他说'再见'」)", "他说'再见'", "raw 串异种引号不转义"),
    ('核说(r"第一行\\n第二行")', "第一行\\n第二行", "raw 串反斜杠是字面"),
    ('核说(rb"\\x41")', "b'\\\\x41'", "raw bytes 反斜杠是字面"),
]
for 源, 期望运行值, 名 in 用例:
    译 = 核.转译(源)
    缓冲 = io.StringIO()
    try:
        代码 = compile(译, "<测试>", "exec")
        with contextlib.redirect_stdout(缓冲):
            exec(代码, {"__name__": "__main__"})
        实际 = 缓冲.getvalue().rstrip("\n")
    except Exception as e:  # noqa: BLE001
        实际 = "<运行失败：%s>" % e
    好 = 实际 == 期望运行值
    print("  %-14s 运行值=%-16r %s" % (名, 实际, "OK" if 好 else "!! 内容变了"))
    if not 好:
        坏 += 1

