# -*- coding: utf-8 -*-
"""内核病态输入：不能死循环、不能崩、不能悄悄改坏内容。"""
import sys
import os
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import 核  # noqa: E402

样本 = [
    ("大量未闭合双引号", 'x = "' * 200),
    ("大量未闭合单引号", "y = '" * 200),
    ("反复左括号", "核说(" * 100),
    ("反复核引号", '核"' * 100),
    ("含空字符", "a\x00b"),
    ("嵌套f串", '核说(核"{' * 50),
    ("十万字符", "a" * 100000),
    ("全角引号未闭合", "核说(「" * 100),
    ("一堆反斜杠", "\\\\" * 1000),
    ("三引号未闭合", '核说("""' + "内容\n" * 100),
    ("只有注释", "核核 " + "x" * 10000),
    ("全角冒号churn", "核若 核对：" * 500),
]

坏 = 0
for 名, s in 样本:
    t = time.perf_counter()
    try:
        译 = 核.转译(s)
        耗 = (time.perf_counter() - t) * 1000
        标 = "OK" if 耗 < 2000 else "!! 慢"
        if 耗 >= 2000:
            坏 += 1
        print("%-16s 长度%-8d %7.1fms  %s" % (名, len(s), 耗, 标))
    except Exception as e:  # noqa: BLE001
        坏 += 1
        print("%-16s !! 抛异常 %s: %s" % (名, type(e).__name__, str(e)[:80]))

# 再验证：字符串内容「原样保留」的承诺在这些病态输入下有没有被违反。
#
# 注意比较方式：不能拿「源码里的写法」去比译文的写法 ——
# 转义符在源码和译文里的表示本来就不同（\t 译出来还是 \t，
# \" 译出来还是 \"）。唯一有意义的标准是**运行时拿到的字符串值**：
# 把译文编出来跑一下，看它实际打印了什么。
print()
print("== 字符串内容是否被悄悄改写（比运行时值，不比写法）==")
import io
import contextlib

用例 = [
    ('核说("a\\tb")', "a\tb", "制表符转义"),
    ('核说("反斜杠 \\\\ 保留")', "反斜杠 \\ 保留", "反斜杠转义"),
    ('核说("「中文引号」")', "「中文引号」", "中文引号原样"),
    ('核说("含\\"转义引号\\"")', '含"转义引号"', "转义双引号"),
    ("核说('单引号里 \"双引号\"')", '单引号里 "双引号"', "单引号包双引号"),
    ('核说("多行\\n换行")', "多行\n换行", "换行转义"),
    ('核说("全角，。；！")', "全角，。；！", "全角标点原样"),
]
for 源, 期望运行值, 名 in 用例:
    译 = 核.转译(源)
    缓冲 = io.StringIO()
    try:
        代码 = compile(译, "<测试>", "exec")
        with contextlib.redirect_stdout(缓冲):
            exec(代码, {"__name__": "__main__"})
        实际 = 缓冲.getvalue().rstrip("\n")
    except Exception as e:  # noqa: BLE001
        实际 = "<运行失败：%s>" % e
    好 = 实际 == 期望运行值
    print("  %-14s 运行值=%-16r %s" % (名, 实际, "OK" if 好 else "!! 内容变了"))
    if not 好:
        坏 += 1

print()
print("=" * 60)
if 坏:
    print("发现 %d 处问题" % 坏)
    sys.exit(1)
print("内核病态输入全部正常")
