# -*- coding: utf-8 -*-
"""方头括号【】：转译、真实运行、字符串/注释保护、行号稳定。

用法：
    python 测试/查方头括号.py

要验证的：
  1. 代码区的【】归一成半角方括号 `[]` —— 中文输入法在中文标点状态下
     按 `[` `]` 键打出来的就是这两个字，想写方括号的人手里拿到的正是它
  2. 列表、下标、切片、嵌套、空列表、连续下标都对
  3. 字符串与注释里的【】一个字不改（「内容保持原样」的承诺）
  4. 转译前后行数不变 —— 报错行号才对得上
  5. 真跑一遍，输出与 Python 原生写法逐字一致
"""

import io
import os
import sys

这里 = os.path.dirname(os.path.abspath(__file__))
根目录 = os.path.dirname(这里)
sys.path.insert(0, 根目录)

import 核  # noqa: E402

失败 = []


def 检查(条件, 说明):
    if 条件:
        print("  ok   %s" % 说明)
    else:
        print("  FAIL %s" % 说明)
        失败.append(说明)


def 译(源码):
    return 核.转译(源码)


def 跑(源码):
    """转译并执行一段核语言，返回它打印出来的文本；编译不过返回 None。"""
    报告 = 核.未定义报告(None)
    代码, _译 = 核.编译源码(源码, "<查方头括号>", 报告)
    if 代码 is None:
        return None
    缓冲 = io.StringIO()
    旧 = sys.stdout
    sys.stdout = 缓冲
    try:
        核.执行代码(代码, 源码, "<查方头括号>", None, 流=缓冲)
    finally:
        sys.stdout = 旧
    return 缓冲.getvalue()


# ---------------------------------------------------------------- 一、归一
def 测归一():
    print("[归一]")

    检查(核.规范化单字("【") == "[", "规范化单字(【) -> [")
    检查(核.规范化单字("】") == "]", "规范化单字(】) -> ]")
    检查(
        核.规范化源码("甲 = 【1】") == "甲 = [1]",
        "规范化源码 把【】折成［］（实际：%r）" % 核.规范化源码("甲 = 【1】"),
    )
    # 与 NFKC 本来就能折的全角方括号一致
    检查(
        核.规范化源码("甲 = ［1］") == 核.规范化源码("甲 = 【1】"),
        "【】与全角［］归一出同一个结果",
    )


# ---------------------------------------------------------------- 二、转译
def 测转译():
    print("[转译]")

    用例 = [
        ("甲 = 【1, 2, 3】", "甲 = [1, 2, 3]", "列表字面量"),
        ("核说(甲【0】)", "print(甲[0])", "下标"),
        ("核说(甲【1：3】)", "print(甲[1:3])", "切片（全角冒号）"),
        ("乙 = 【【1】, 【2】】", "乙 = [[1], [2]]", "嵌套"),
        ("核说(【】)", "print([])", "空列表"),
        ("核说(【\"甲\", \"乙\"】【1】)", 'print(["甲", "乙"][1])', "字面量后直接下标"),
        ("甲【0】 = 9", "甲[0] = 9", "下标赋值"),
        ("核用 i 遍历 【1, 2】：", "for i in [1, 2]:", "遍历列表"),
    ]
    for 源, 期望, 说明 in 用例:
        实得 = 译(源 + "\n").rstrip("\n")
        检查(实得 == 期望, "%s：%s -> %s（实际：%s）" % (说明, 源, 期望, 实得))


# ---------------------------------------------------------------- 三、保护
def 测保护():
    print("[字符串与注释保持原样]")

    实得 = 译('核说("【不是括号】")\n').rstrip("\n")
    检查(
        实得 == 'print("【不是括号】")',
        "字符串里的【】不被改写（实际：%s）" % 实得,
    )

    实得 = 译("核核 【注释里】\n").rstrip("\n")
    检查(实得 == "# 【注释里】", "注释里的【】不被改写（实际：%s）" % 实得)

    实得 = 译('核说(核"【{甲}】")\n').rstrip("\n")
    检查(
        实得 == 'print(f"【{甲}】")',
        "f-string 里括号外的【】保持原样（实际：%s）" % 实得,
    )

    # 字符串里的【】也不能被当成括号去配对：跨行字符串里的【 不该影响结构
    实得 = 译('核说("左【")\n核说("右】")\n')
    检查(
        实得 == 'print("左【")\nprint("右】")\n',
        "两行里的半个【】互不干扰（实际：%r）" % 实得,
    )


# ---------------------------------------------------------------- 四、行号
def 测行号():
    print("[行号稳定]")

    源 = "甲 = 【1,\n     2】\n核说(甲)\n"
    译后 = 译(源)
    检查(
        len(译后.splitlines()) == len(源.splitlines()),
        "转译前后行数一致（%d vs %d）" % (len(源.splitlines()), len(译后.splitlines())),
    )
    检查("[" in 译后 and "]" in 译后, "跨行方头括号也折对了（实际：%r）" % 译后)


# ---------------------------------------------------------------- 五、真跑
def 测真实运行():
    print("[真实运行]")

    用例 = [
        ("甲 = 【1, 2, 3】\n核说(甲【0】)\n", "1\n", "下标取值"),
        ("核说(【1, 2, 3】【1】)\n", "2\n", "字面量直接下标"),
        ("核说(【0, 1, 2, 3, 4】【1：3】)\n", "[1, 2]\n", "切片"),
        ("核说(【【1】, 【2】】)\n", "[[1], [2]]\n", "嵌套原样打印"),
        ("甲 = 【1, 2】\n甲【0】 = 9\n核说(甲)\n", "[9, 2]\n", "下标赋值"),
        ("核用 i 遍历 【1, 2, 3】：\n    核说(i)\n", "1\n2\n3\n", "遍历"),
        ('核说("【】")\n', "【】\n", "字符串里原样输出"),
    ]
    for 源, 期望, 说明 in 用例:
        实得 = 跑(源)
        检查(实得 == 期望, "%s：期望 %r，实际 %r" % (说明, 期望, 实得))

    # 与 Python 原生写法逐字对比（不是只跟转译结果比）
    源 = "甲 = 【3, 1, 2】\n核说(核长度(甲))\n核说(甲【1】)\n"
    实得 = 跑(源)
    检查(实得 == "3\n1\n", "与 Python 原生写法结果一致（实际：%r）" % 实得)


# ---------------------------------------------------------------- 六、混用
def 测混用():
    print("[与其它括号混用]")

    检查(
        译("核说（【1, 2】）\n").rstrip("\n") == "print([1, 2])",
        "全角圆括号里套方头括号",
    )
    检查(
        译("核说(（1 + 2）【0】)\n").rstrip("\n") == "print((1 + 2)[0])",
        "圆括号表达式后接方头括号下标",
    )
    检查(
        译("甲 = ｛\"k\"： 【1】｝\n").rstrip("\n") == '甲 = {"k": [1]}',
        "字典值里放方头括号列表",
    )


def 主():
    print("=" * 56)
    print("方头括号【】检查")
    print("=" * 56)
    测归一()
    测转译()
    测保护()
    测行号()
    测真实运行()
    测混用()
    print("-" * 56)
    if 失败:
        print("失败 %d 项：" % len(失败))
        for 项 in 失败:
            print("  · %s" % 项)
        return 1
    print("全部通过")
    return 0


if __name__ == "__main__":
    sys.exit(主())
