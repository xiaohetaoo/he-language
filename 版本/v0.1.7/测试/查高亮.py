# -*- coding: utf-8 -*-
"""高亮：字符串、注释、关键字三者的优先级与边界。

要点（每一条都是实测踩过的）：
  · 字符串**里面**的关键字/内置名/数字不能被染成关键字色 ——
    以前规则按列表顺序 finditer + setFormat，字符串规则排第一，
    后染的会把字符串里的「核若」「核长度」盖成关键字色/内置色。
  · 三引号串跨行时，第 2 行起也要染成字符串色（以前每行独立染色，
    续行没有开头引号就完全不上色）。
  · 全角/中文引号 「」『』“” 内核当字符串边界，高亮必须同样处理。
  · 注释里的引号不是字符串开头；字符串里的「核核」不是注释开头。

做法：真的建高亮器、真的 rehighlight，然后按字符位置读它染了什么颜色。

用法：python 测试/查高亮.py
"""

import os
import sys
import tempfile

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ.setdefault("核工坊_配置目录", tempfile.mkdtemp(prefix="核工坊高亮色_"))

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from PySide6.QtGui import QColor  # noqa: E402
from PySide6.QtWidgets import QApplication  # noqa: E402

import 核工坊Qt  # noqa: E402

应用 = QApplication.instance() or QApplication(sys.argv)
窗 = 核工坊Qt.主窗()

问题 = []


def 色表(编):
    """返回 {行号: [(起, 止, 颜色名), …]}，只含被染色过的片段。"""
    结果 = {}
    块 = 编.document().firstBlock()
    while 块.isValid():
        段 = []
        for r in 块.layout().formats():
            色 = r.format.foreground().color().name().upper()
            段.append((r.start, r.start + r.length, 色))
        结果[块.blockNumber()] = 段
        块 = 块.next()
    return 结果


def 查色(编, 行, 列, 期望键, 说明):
    """第 行（0 起）第 列（0 起）那个字符应染成 期望键 对应的颜色。"""
    目标 = QColor(窗.主题[期望键]).name().upper()
    段 = 色表(编).get(行, [])
    命中 = [s for s in 段 if s[0] <= 列 < s[1]]
    实 = 命中[-1][2] if 命中 else None
    if 实 == 目标:
        print("  OK  %s" % 说明)
    else:
        问题.append((说明, 行, 列, 期望键, 实))
        print("  !! %s（行%d 列%d 期望 %s=%s，实际 %s）"
              % (说明, 行, 列, 期望键, 目标, 实))


def 建(文本):
    编 = 窗.当前 or 窗.新建()
    编.置文本(文本)
    高 = 编.高亮
    高.重建()
    高.rehighlight()
    应用.processEvents()
    return 编


print("== 一、字符串里的关键字/内置名不能被覆盖 ==")
编 = 建('核说("核若 核长度 123")\n')
#           0123456789...
# 核说("  —— 0..3；字符串内容从第 4 列开始
查色(编, 0, 3, "字符串", "字符串起引号是字符串色")
for 列, 字 in ((4, "核"), (7, "核"), (10, "1")):
    查色(编, 0, 列, "字符串", "字符串里的 %r 仍是字符串色" % 字)
# 核说 是内置函数（在函数表里），所以是内置色而不是关键字色 ——
# 关键字色只给 关键词表 里的那些（核若/核用/核定义…）。
查色(编, 0, 0, "内置", "函数名 核说 仍是内置色")
# 核长度 是内置名，但它在这里位于字符串**内部**，必须是字符串色
查色(编, 0, 7, "字符串", "字符串里的 核长度 不上内置色")

print("== 一之二、字符串外的关键字要正常上关键字色 ==")
编 = 建("核若 核对：\n    核说(1)\n")
查色(编, 0, 0, "关键字", "核若 是关键字色")
查色(编, 0, 3, "关键字", "核对 是关键字色")
查色(编, 1, 4, "内置", "核说 是内置色")

print("== 二、注释里的引号不是字符串 ==")
编 = 建('核核 说明 "这不是字符串"\n')
查色(编, 0, 0, "注释", "注释引导词是注释色")
查色(编, 0, 7, "注释", "注释里的引号仍是注释色")
查色(编, 0, 12, "注释", "注释后半段仍是注释色")

print("== 二之二、注释里的关键字/内置名/数字也不能被覆盖 ==")
# 和「字符串里不能染关键字」是同一个毛病：规则是按列表顺序后染覆盖先染的，
# 注释先染、关键字/内置/数字随后就把它盖花了 ——
# 一条注释看起来花花绿绿像代码。
编 = 建("核核 核说(1) 核若 123\n")
# 核0 核1 空2 核3 说4 (5 1(6) )7 空8 核9 若10 空11 1(12)2(13)3(14)
for 列, 字 in ((3, "核说"), (6, "数字 1"), (9, "核若"), (13, "数字 23")):
    查色(编, 0, 列, "注释", "注释里的 %s 仍是注释色" % 字)

print("== 三、字符串里的「核核」不是注释 ==")
编 = 建("核说('核核 在字符串里')\n")
查色(编, 0, 4, "字符串", "字符串里第一个 核 是字符串色")
查色(编, 0, 5, "字符串", "字符串里第二个 核 是字符串色")

print("== 四、三引号跨行 ==")
编 = 建('核说("""第一行\n第二行 核若\n""")\n')
查色(编, 0, 3, "字符串", "三引号串第 1 行是字符串色")
查色(编, 1, 0, "字符串", "三引号串第 2 行（续行）是字符串色")
查色(编, 1, 4, "字符串", "续行里的 核若 也是字符串色")
查色(编, 2, 0, "字符串", "三引号收尾行是字符串色")

print("== 五、全角/中文引号 ==")
编 = 建("核说(「中文」)\n")
查色(编, 0, 3, "字符串", "「 开引号是字符串色")
查色(编, 0, 4, "字符串", "「」里的内容在字符串里")
编 = 建("核说(“中文”)\n")
查色(编, 0, 3, "字符串", "“ 开引号是字符串色")
编 = 建("核说(‘中文’)\n")
查色(编, 0, 3, "字符串", "‘ 开引号是字符串色")

print("== 六、ASCII 引号里的全角右引号不收尾 ==")
# 曾经把 」 算进 " 的收尾集，于是这一行的字符串在第 3 个字符就断了
编 = 建('核说("成绩里没有「数学」这一项")\n')
# 核0 说1 (2 "3 成4 绩5 里6 没7 有8 「9 数10 学11 」12 这13 一14 项15 "16 )17
查色(编, 0, 9, "字符串", "「 之后仍在字符串里")
查色(编, 0, 12, "字符串", "」 不能提前结束 ASCII 引号串")
查色(编, 0, 15, "字符串", "收尾引号之前都在字符串里")
查色(编, 0, 16, "字符串", "收尾引号本身是字符串色")

print("== 七、块开头：字符串里的冒号不算 ==")
检 = 核工坊Qt.编辑器.是块开头
for 文本, 期望, 说明 in (
    ("核若 x：", True, "全角冒号"),
    ("核若 x:", True, "半角冒号"),
    ("核若 x： 核核 说明", True, "行尾注释不影响"),
    ("核说(1)", False, "普通语句"),
    ('核说("a:")', False, "字符串里的冒号不算"),
    ("核核 注释：", False, "整行是注释"),
):
    if 检(文本) == 期望:
        print("  OK  %s" % 说明)
    else:
        问题.append((说明, 文本, None, 期望, 检(文本)))
        print("  !! %s（%r）" % (说明, 文本))

print()
print("=" * 62)
if 问题:
    print("发现 %d 处高亮问题：" % len(问题))
    for 项 in 问题:
        print("  · %s" % (项[0],))
    sys.exit(1)
print("高亮优先级与边界全部正常")
