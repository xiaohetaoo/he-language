# -*- coding: utf-8 -*-
"""主题色对比度守卫。

不是「看起来还行」—— 直接把 WCAG 对比度算出来卡阈值。
这一项是从审查报告里长出来的：浅色主题的选中行字曾经写死 #FFFFFF，
压在 #D5E5FF 浅蓝底上只有 1.1:1，设置窗口左栏、快速打开、项目树
三处都几乎看不见（有截图实拍，几乎读不出「外观」两个字）。

所以这里守两件事：
  1. 关键的前景/背景组合对比度达标；
  2. QSS 里不许再写死 #FFFFFF 去盖浅色底 —— 那类位置必须走色表键，
     否则换主题时它不会跟着变。

用法：python 测试/查对比度.py
"""

import os
import re
import sys

这里 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 这里)

import 主题  # noqa: E402

问题 = []
检查数 = 0


def 亮度(十六进制):
    值 = 十六进制.lstrip("#")
    r, g, b = (int(值[i:i + 2], 16) / 255 for i in (0, 2, 4))

    def 分量(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * 分量(r) + 0.7152 * 分量(g) + 0.0722 * 分量(b)


def 对比度(前景, 背景):
    甲, 乙 = 亮度(前景), 亮度(背景)
    亮, 暗 = max(甲, 乙), min(甲, 乙)
    return (亮 + 0.05) / (暗 + 0.05)


def 检(说明, 前景键, 背景键, 阈值):
    global 检查数
    检查数 += 1
    前景 = 色.get(前景键)
    背景 = 色.get(背景键)
    if not 前景 or not 背景:
        问题.append("%s：色表缺键（%s=%r %s=%r）" % (说明, 前景键, 前景, 背景键, 背景))
        return
    比 = 对比度(前景, 背景)
    if 比 < 阈值:
        问题.append(
            "%s：%s(%s) 压 %s(%s) 只有 %.2f:1，要求 ≥ %.1f"
            % (说明, 前景键, 前景, 背景键, 背景, 比, 阈值)
        )
    else:
        print("  OK  %s：%.2f:1（≥ %.1f）" % (说明, 比, 阈值))


for 主题名, 色 in 主题.主题集.items():
    print("== %s ==" % 主题名)
    # 正文与次要文字（WCAG 正文要求 4.5:1）
    检("正文 / 编辑器底", "文本", "编辑器", 4.5)
    检("正文 / 面板底", "文本", "面板", 4.5)
    检("正文 / 浮层底", "文本", "浮层", 4.5)
    检("次要文字 / 面板底", "次要文本", "面板", 4.5)
    检("行号字 / 行号底", "行号字", "行号底", 4.5)
    检("控制台字 / 控制台底", "控制台字", "控制台底", 4.5)
    # 选中行：这是审查报告里实锤的那一条 —— 深色和浅色都必须能读
    检("选中行字 / 选中行底", "选中行字", "选中行", 4.5)
    # 实心按钮：白字压在「按钮底」上
    白 = "#FFFFFF"
    比 = 对比度(白, 色["按钮底"])
    检查数 += 1
    if 比 < 4.5:
        问题.append("白字 / 按钮底：%s 上白字只有 %.2f:1，要求 ≥ 4.5" % (色["按钮底"], 比))
    else:
        print("  OK  白字 / 按钮底：%.2f:1（≥ 4.5）" % 比)
    # diff 预览：增/删行的字压在各自的底色上
    检("diff 增行字 / 增行底", "diff增字", "diff增底", 4.5)
    检("diff 删行字 / 删行底", "diff删字", "diff删底", 4.5)
    # 当前行是「弱提示」，不按正文标准；但也不能和编辑器底完全一样
    # （曾经因为 FullWidthSelection 的魔数写错，整行根本没画出来）
    比 = 对比度(色["当前行"], 色["编辑器"])
    检查数 += 1
    if 比 < 1.05:
        问题.append("当前行 / 编辑器底：%.2f:1，几乎完全看不出来" % 比)
    else:
        print("  OK  当前行 / 编辑器底：%.2f:1（≥ 1.05，弱提示可辨）" % 比)

print()
print("== QSS 里不许写死 #FFFFFF 盖浅色底 ==")
qss = 主题._QSS
# 只关心「选中行」这类会落在浅色底上的规则。按钮/菜单那几处是实心蓝底，
# 白字本来就够（上面的对比度检查已经覆盖），列出来是为了让人一眼看懂
# 为什么允许它们存在。
允许 = ("关闭钮", "QMenu::item:selected", "QPushButton", "background: __按钮底__")
命中 = []
for 行号, 行 in enumerate(qss.splitlines(), 1):
    if "#FFFFFF" not in 行:
        continue
    内容 = " ".join(允许) in 行 or any(词 in 行 for 词 in 允许)
    if 内容:
        continue
    命中.append((行号, 行.strip()))
检查数 += 1
if 命中:
    for 行号, 行 in 命中:
        问题.append("QSS 第 %d 行写死 #FFFFFF：%s" % (行号, 行))
else:
    print("  OK  QSS 里剩下的 #FFFFFF 全在实心按钮/菜单/关闭钮上（对比度已达标）")

print()
print("=" * 62)
print("共检查 %d 项" % 检查数)
if 问题:
    print("发现 %d 处问题：" % len(问题))
    for 条 in 问题:
        print("  · %s" % 条)
    sys.exit(1)
print("主题对比度全部达标")
