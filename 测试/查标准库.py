# ------------------------------------------------------- 二、成员是否真实存在
def 测赋值不覆盖():
    """模块名 / 库成员名写在赋值左边时，必须原样保留。

    0.1.9 引入的回归：`数学库 = 5` 被译成 `math = 5`，标准库被静默顶掉，
    之后 `核数学库.核平方根(4)` 报 `AttributeError: 'int' object has no
    attribute 'sqrt'` —— 用户代码全中文，报错里却冒出 math/sqrt。
    """
    print()
    print("[赋值不覆盖]")

    for 源码, 词 in (
        ("数学库 = 5\n", "math"),
        ("核数学库 = 5\n", "math"),
        ('随机库 = "x"\n', "random"),
        ("核随机库 = 1\n", "random"),
        ("核正弦 = 5\n", "sin"),
    ):
        译 = 核.转译(源码)
        检查(
            词 not in 译,
            "`%s` 的译文里不出现 %s（实际：%r）" % (源码.strip(), 词, 译.strip()),
        )

    # 绑定位置要认全：赋值、复合赋值、循环目标、函数名、类名、核删 目标。
    # 只认纯 `=` 的话，`核正弦 += 1` / `核用 核正弦 核在 …` 这些位置的
    # 名字在引用处仍会被译成 sin（口径分裂，见 0.2.1 的修复）。
    for 源码, 说明 in (
        ("核正弦 = 5\n核说(核正弦)\n", "赋值处与引用处都保留中文名"),
        ("核正弦 += 1\n", "复合赋值 += 算绑定"),
        ("核正弦 -= 1\n核余弦 *= 2\n", "复合赋值 -= / *= 算绑定"),
        ("核正弦 //= 2\n核余弦 **= 2\n", "复合赋值 //= / **= 算绑定"),
        ("核用 核正弦 核在 核数列(3)：\n    核说(核正弦)\n", "循环目标不算模块名"),
        ("核用 核正弦, 核余弦 核在 核数列(3)：\n    核略过\n", "循环目标并列都算绑定"),
        ("核定义 核正弦()：\n    核略过\n", "函数名不算模块名"),
        ("核类 核随机库：\n    核略过\n", "类名不算模块名"),
        ("核删 核正弦\n", "核删 目标不算模块名"),
    ):
        译 = 核.转译(源码)
        检查(
            "sin" not in 译 and "cos" not in 译 and "random" not in 译,
            "%s（实际：%r）" % (说明, 译.strip()),
        )

    检查(
        "核正弦" in 核.转译("核正弦 = 5\n核说(核正弦)\n"),
        "同名两处都是中文（引用处没被译成 sin）",
    )

    # 属性位不是模块段：点号前那一段有两种身份 ——
    #     模块段  核数学库.核正弦    （该译）
    #     属性段  甲.数学库.核正弦    （甲 的属性，不能改名）
    # 只看「后面跟不跟点」分不出来，所以要靠 `上一个是点` 区分。
    for 源码, 坏词 in (
        ("甲.数学库.核正弦(1)\n", "math"),
        ("甲.随机库.核随机整数(1, 6)\n", "random"),
        ("甲.数学库 = 1\n甲.数学库.核值 = 2\n", "math"),
    ):
        译 = 核.转译(源码)
        检查(
            坏词 not in 译,
            "属性段不改名：%s（实际：%r）"
            % (源码.strip().replace(chr(10), " / "), 译.strip()),
        )
    检查("甲.数学库" in 核.转译("甲.数学库\n"), "单独写属性也保留原样")

    # 用户变量被赋过值之后，属性访问打到自己身上，不该被静默换成 math
    译 = 核.转译("核导入 核数学库\n数学库 = 5\n核说(数学库.核正弦(1))\n")
    检查(
        "print(数学库.sin(1))" in 译 and "math.sin" not in 译,
        "同名变量被赋过值后，属性访问不再走 math（实际：%r）" % 译.strip(),
    )

    # import 行有自己的语法：即使这个名字在别处被赋过值，这里也照译 ——
    # 否则 `from math import 核正弦` 直接 ImportError。
    译 = 核.转译(
        "核从 核数学库 核导入 核正弦\n核正弦 = 5\n核说(核正弦)\n"
    )
    检查("from math import sin" in 译, "import 行的成员名照译（不受同名赋值影响）")
    检查("print(核正弦)" in 译, "裸名引用按变量算（有意的不对称）")

    # 复合场景：导入照常、变量保持原名、调用仍走 math
    复合 = "核导入 核数学库\n数学库 = 0\n核说(核数学库.核平方根(4))\n"
    译 = 核.转译(复合)
    检查("import math" in 译, "复合场景：模块照常导入")
    检查("数学库 = 0" in 译, "复合场景：变量保持原名")
    检查("math.sqrt(4)" in 译, "复合场景：调用仍走 math")

    # 关键词本来就禁止当变量名，这条现状不能变
    检查("if = 5" in 核.转译("核若 = 5\n"), "关键词仍禁止当变量名")

    # —— 0.2.4 修：函数参数名与库成员同名 ——
    # `核定义 取值(核正弦):` 里 核正弦 是**绑定**（参数名）。以前
    # 定义侧被「是参数」分支豁免译成了 sin，而调用侧 `取值(核正弦=5)`
    # 同样是「是参数」形态（前面是 `(` 后面是 `=`），也豁免保留中文 ——
    # 两侧名对不上，Python 报 unexpected keyword argument。
    # 修法：扫绑定名 把参数名也收进绑定集，两侧就都用同一个名字。
    _译 = 核.转译(
        "核定义 取值(核正弦):\n"
        "    核返回 核正弦 * 2\n"
        "核说(取值(核正弦=5))\n"
    )
    # 判据是「两侧一致」，不是「必须译成 sin」—— 参数名是绑定，
    # 按「被绑过的名字不当作库成员」的既有规则，两侧都保留中文也对。
    _定义侧 = [行 for 行 in _译.splitlines() if 行.lstrip().startswith("def ")]
    _调用侧 = [行 for 行 in _译.splitlines() if "取值(" in 行 and "def" not in 行]
    _一致 = bool(_定义侧) and bool(_调用侧) and (
        ("sin" in _定义侧[0]) == ("sin" in _调用侧[0])
    )
    检查(_一致, "参数名与库成员同名时两侧一致（实际：%r）" % _译.strip())
    _实 = 跑(
        "核定义 取值(核正弦):\n"
        "    核返回 核正弦 * 2\n"
        "核说(取值(核正弦=5))\n"
    )
    检查(_实 == "10\n", "参数名同库成员能真的跑通（实际：%r）" % _实)

def 测成员存在():
    print()
    print("[成员真实性]")
    # 模块实例由 核.模块表 推导，不手写清单 —— 0.2.3 加了 time/os/sys/json
    # 之后，写死 math/random 会让这条检查变成「只测两个老模块」。
    import importlib

    实例 = {}
    for 英 in sorted(set(核.模块表.values())):
        实例[英] = importlib.import_module(英)

    缺 = []
    for 中, 英 in sorted(核.库成员表.items()):
        if not any(hasattr(m, 英) for m in 实例.values()):
            缺.append("%s -> %s" % (中, 英))
    检查(
        not 缺,
        "库成员表里每个英文名都真实存在%s" % ("（不存在：%s）" % "、".join(缺) if 缺 else ""),
    )

    # 单独点出 cbrt：3.11 才有，低版本会 AttributeError
    检查(
        hasattr(math, "cbrt"),
        "math.cbrt 存在（Python %d.%d，该函数需要 3.11+）"
        % (sys.version_info[0], sys.version_info[1]),
    )

    检查(
        核.模块表.get("核数学库") == "math" and 核.模块表.get("核随机库") == "random",
        "模块表把两个库指向 math / random",
    )


