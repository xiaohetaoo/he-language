    检查(not 交, "库成员与函数不同名%s" % ("（撞到：%s）" % "、".join(sorted(交)) if 交 else ""))

    交 = set(核.模块表) & (set(核.函数表) | set(核.方法表) | set(核.关键词表))
    检查(not 交, "模块名不与函数/方法/关键字同名%s" % ("（撞到：%s）" % "、".join(sorted(交)) if 交 else ""))

