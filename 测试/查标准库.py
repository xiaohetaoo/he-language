def 测漏导入线索():
    """没写 `核导入` 就用裸名库成员时，报错要指出该补哪一句导入。

    库成员表 让 `核正弦` 在裸名位置直接译成 `sin`，于是报错里冒出的是
    `NameError: name 'sin' is not defined` —— 中文源码里凭空多出一个 sin，
    不给线索的话完全不知道该补什么。
    """
    print()
    print("[漏导入线索]")

    出 = 跑("核说(核正弦(1))\n")
    检查(出 is not None, "编译通过（转译本身不报错）")
    if 出 is None:
        return
    检查(
        "核从 核数学库 核导入 核正弦" in 出,
        "NameError 线索给了**有效**补法 `核从 核数学库 核导入 核正弦`（实际：%r）"
        % 出.strip()[:160],
    )
    检查(
        "核正弦" in 出,
        "线索里给出了这个成员的中文名（实际：%r）" % 出.strip()[:160],
    )

    # 模块名的漏导入要单独说 —— 和成员名的有效补法不一样：
    # 成员名要 `核从 … 核导入 …`；模块名只要 `核导入 …` 然后带前缀用。
    for 源码, 说明 in (
        ("甲 = 核数学库\n甲.核平方根(4)\n", "中文模块名 核数学库 的 NameError"),
        ("核说(math.pi)\n", "英文模块名 math 的 NameError"),
    ):
        出 = 跑(源码)
        检查(
            出 is not None and "标准库模块名" in 出 and "核导入 核数学库" in 出,
            "%s 有线索（实际：%r）" % (说明, (出 or "").strip()[:150]),
        )

    # AttributeError 的文案要说「点号前对象不对」，不能再说「被同名变量顶掉」——
    # 0.2.1 起用户变量根本顶不掉模块（`核数学库 = 5` 是普通变量，
    # `核数学库.核正弦` 仍走 math），那条归因已经不成立。
    出 = 跑("甲 = 5\n核说(甲.核正弦(1))\n")
    检查(
        出 is not None and "不是核数学库" in 出,
        "AttributeError 线索指出点号前面的对象不对（实际：%r）" % (出 or "").strip()[:150],
    )
    检查(
        出 is not None and "顶掉" not in 出,
        "AttributeError 线索不再说「顶掉」（实际：%r）" % (出 or "").strip()[:150],
    )

    # 写了导入就照常跑，不该冒线索
    出 = 跑("核导入 核数学库\n核说(核数学库.核正弦(0))\n")
    检查(
        出 is not None and "运行出错" not in 出,
        "写了导入就正常跑通（实际：%r）" % (出 or "").strip()[:80],
    )

def 测并列异常():
    """无括号并列异常要自动补括号，否则产物是非法 Python。

    `核异常 值错误, 类型错误：` 照字面翻译会得到 `except ValueError, TypeError:`——
    那是 Python 2 的写法，Python 3 直接 invalid syntax；而 _语法线索 只会落到
    「看看是不是拼错」的兜底上，指错方向。
    """
    print()
    print("[并列异常]")

    for 源码, 期望, 说明 in (
        (
            "核异常 值错误, 类型错误：\n    核略过\n",
            "except (ValueError, TypeError):",
            "无括号并列自动补括号",
        ),
        (
            "核异常 值错误, 类型错误 核作为 错：\n    核略过\n",
            "except (ValueError, TypeError) as 错:",
            "核作为 留在括号外",
        ),
        (
            "核异常 (值错误, 类型错误)：\n    核略过\n",
            "except (ValueError, TypeError):",
            "已经写过括号的不重复补",
        ),
        ("核异常 值错误：\n    核略过\n", "except ValueError:", "单个类型不加括号"),
        (
            '核抛出 权限错误("x")\n',
            'raise PermissionError("x")',
            "核抛出 的调用括号不会被误判成并列",
        ),
    ):
        译 = 核.转译(源码)
        首行 = 译.splitlines()[0] if 译 else ""
        检查(期望 in 译, "%s（实际：%r）" % (说明, 首行))

    # 真跑一遍：补出来的括号要真能接住
    出 = 跑(
        "核试：\n"
        '    核抛出 值错误("x")\n'
        "核异常 值错误, 类型错误：\n"
        '    核说("接住了")\n'
    )
    检查(
        出 is not None and "接住了" in 出,
        "补出括号后真能接住 ValueError（实际：%r）" % (出 or "").strip()[:90],
    )

    # _语法线索 要有专门规则，不再落进 invalid syntax 兜底
    线索 = 核._语法线索("multiple exception types must be parenthesized")
