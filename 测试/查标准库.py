def 检查(条件, 说明):
    if 条件:
        print("  ok   %s" % 说明)
    else:
        print("  FAIL %s" % 说明)
        失败.append(说明)


def 跑(源码):
    """转译并执行一段核语言，返回它打印出来的文本；编译不过返回 None。"""
    报告 = 核.未定义报告(None)
    代码, _译 = 核.编译源码(源码, "<查标准库>", 报告)
    if 代码 is None:
        return None
    缓冲 = io.StringIO()
    旧 = sys.stdout
    sys.stdout = 缓冲
    try:
        核.执行代码(代码, 源码, "<查标准库>", None, 流=缓冲)
    finally:
        sys.stdout = 旧
    return 缓冲.getvalue()


